CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 session_version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_attempts (
 fingerprint CHAR(64) PRIMARY KEY,
 failures INT UNSIGNED NOT NULL DEFAULT 0,
 last_attempt DATETIME NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS bagian (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 kd_bagian VARCHAR(5) NOT NULL UNIQUE,
 nama_bagian VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS karyawan (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nip VARCHAR(15) NOT NULL UNIQUE,
 nama VARCHAR(150) NOT NULL,
 kd_bagian VARCHAR(5) NOT NULL,
 gapok DECIMAL(18,0) NULL DEFAULT 0,
 t_jabatan DECIMAL(18,0) NULL DEFAULT 0,
 t_harian DECIMAL(18,0) NULL DEFAULT 0,
 t_lembur DECIMAL(18,0) NULL DEFAULT 0,
 KEY ix_bagian(kd_bagian)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tunj_jam (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nip VARCHAR(15) NOT NULL UNIQUE,
 jumlah DECIMAL(18,0) NULL DEFAULT 0,
 tarip DECIMAL(18,0) NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NULL,
 action VARCHAR(30) NOT NULL,
 entity VARCHAR(80) NOT NULL,
 record_key VARCHAR(150) NOT NULL,
 before_data JSON NULL,
 after_data JSON NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY ix_entity(entity,record_key)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS migration_runs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source_sha256 CHAR(64) NOT NULL,
 source_database VARCHAR(128) NOT NULL,
 status VARCHAR(30) NOT NULL,
 summary JSON NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS legacy_tables (
 table_name VARCHAR(256) PRIMARY KEY,
 row_count BIGINT UNSIGNED NOT NULL,
 schema_data JSON NOT NULL,
 content_sha256 CHAR(64) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS legacy_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 table_name VARCHAR(256) NOT NULL,
 source_ordinal BIGINT UNSIGNED NOT NULL,
 payload LONGTEXT NOT NULL,
 row_sha256 CHAR(64) NOT NULL,
 UNIQUE KEY uq_source(table_name,source_ordinal)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS app_settings (
 setting_key VARCHAR(100) PRIMARY KEY,
 setting_value LONGTEXT NOT NULL
) ENGINE=InnoDB;
